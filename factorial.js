function factorialIterative(n) {
    if (n < 0) {
        return "Factorial is not defined for negative numbers";
    }
    let result = 1;
    for (let i = 1; i <= n; i++) {
        result *= i;
    }
    return result;
}

// Example: User input
let num = parseInt(prompt("Enter a number: "));
console.log("Factorial of " + num + " is: " + factorialIterative(num));
